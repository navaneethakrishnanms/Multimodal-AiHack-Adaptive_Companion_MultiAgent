"""Render DEVPOST_TEXT.md from eval_report.json (every number comes from the report). Does not submit anything."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = json.loads((ROOT / "eval_report.json").read_text(encoding="utf-8"))
ret, gate, a = R["retrieval"], R["retrieval_gate"], R["assessment"]
ml, os_ = R["personalization"]["ml"], R["personalization"]["os"]
gen = R.get("generation") or {}
online = R["llm"]["healthy"]


def pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def row(res: dict, key: str) -> str:
    pb = res["paired_vs_baselines"][key]
    sig = "significant" if pb["ci95"][0] > 0 or pb["ci95"][1] < 0 else "not significant"
    return f"{pb['mean_diff']:+.2f} (95% CI {pb['ci95'][0]:+.2f} to {pb['ci95'][1]:+.2f}, {sig})"


faith = gen.get("faithfulness", {})
faith_line = (f"Faithfulness {faith['score']} and answer relevancy {gen['answer_relevancy']['score']} "
              f"(LLM-judged, n={faith['n']}, model {R['llm']['model']})." if faith.get("score") is not None else
              "Faithfulness and answer relevancy were **not measured** in the evaluation run on file (it ran without a working language "
              "model); the scripts compute them automatically when one is connected.")

text = f"""# Devpost text — Study Companion (Track D)

_Generated by `scripts/make_devpost.py` from `eval_report.json` ({R.get('generated_at', '?')}; LLM during that run: {'online, ' + R['llm']['model'] if online else 'offline'}). Do not edit numbers by hand; re-run the evaluation and this script instead._

## Inspiration
Students study from slides, textbooks and lecture videos scattered across places, and general chatbots answer without tying anything to the course — or to what the student already understands. We wanted a tutor that is accountable to the material and models the learner.

## What it does
Study Companion unifies PDFs, slide decks, lecture recordings and notes into one source-linked knowledge base and uses it for tutoring and adaptive assessment.

- **Multimodal ingestion** — PDF pages, slides, timestamped transcripts, and audio/video transcribed with Whisper. Figures in PDFs and slides are extracted, stored as citable units and described by a vision model when one is connected (otherwise explicitly flagged as not described).
- **Source-grounded tutor** — answers only from retrieved excerpts, cites them, and the Source Viewer opens the exact PDF page, slide, or video timestamp. Questions the material does not cover are declined and flagged; a general-knowledge answer is available only on request and is visibly separated.
- **Adaptive assessment** — MCQ / short / numerical questions tagged with topic, source and difficulty, verified by an independent pass (optionally a second model), deduplicated per student, with cited feedback and a post-assessment report of weak topics and likely misconceptions.
- **Learner model** — Bayesian knowledge tracing per topic and student, cold-start diagnostic quiz and intake, forgetting-curve study schedule, next-best-action recommendations that state their reasons, flashcards and spoken briefs, Hindi answers and voice input.
- **RootCause (our differentiator)** — when a student misses a topic, the system blames its prerequisites (weak or never-tested ones most), probes the top suspect with two verified questions, lowers that prerequisite's mastery only from the probe answers, and returns a repair path of source links followed by a re-test.

## How we built it
Python / FastAPI backend, a single-file Tailwind + vanilla JS front end with Cytoscape for the prerequisite graph, scikit-learn TF-IDF retrieval with a calibrated refusal gate, faster-whisper, PyMuPDF and python-pptx for ingestion, and any OpenAI-compatible model for generation, verification and vision. Every LLM feature degrades to a deterministic offline mode.

## Evaluation (all numbers from `eval_report.json`)
Test set: {R['testset']['in_material']} in-material questions with ground-truth source locations and {R['testset']['off_material']} off-material queries (including near-miss ones) over two sample courses.

- **Retrieval (top-{ret['k']}):** hit rate {pct(ret['hit_rate'])}, MRR {ret['mrr']}, context precision {ret['context_precision']}, context recall {ret['context_recall']} (ID-based, RAGAS definitions implemented natively).
- **Refusal gate** (calibrated on a dev split, reported on a held-out split of {gate['test']['n_in']} + {gate['test']['n_off']} queries): refuses {pct(gate['test']['refused_off_material'])} of off-material queries (no gate: {pct(gate['no_gate_baseline_test']['refused_off_material'])}) while answering {pct(gate['test']['answered_in_material'])} of in-material ones; the recall-first online gate answers {pct(gate['online_gate_test']['answered_in_material'])} and refuses {pct(gate['online_gate_test']['refused_off_material'])}.
- **Generation:** {faith_line}
- **Assessment audit** ({a['questions']} questions, mode: {a['mode']}): {pct(a['verified_rate'])} verified, {pct(a['tag_consistency'])} tag-consistent, {pct(a['repeat_rate_across_assessments'])} repeated across assessments.
- **Personalization (simulated latent-gap students, 30 per course, paired, 6 sessions × 4 questions):** RootCause vs plain BKT weakest-first, F1 of diagnosed root causes: ML course {row(ml, 'C_minus_B.f1_R')}; OS course {row(os_, 'C_minus_B.f1_R')}. True gap closure vs weakest-first: ML {row(ml, 'C_minus_B.gain')}; OS {row(os_, 'C_minus_B.gain')}.

## Challenges and honest limitations
- Simulated students encode our assumptions about prerequisite structure; the results show the policy exploits that structure, not that real students improve.
- RootCause does not beat a plain fixed-order sweep on every metric (see `docs/EVALUATION.md` for the full tables, ablation and sensitivity runs).
- Sample courses are small ({R['testset']['courses']['ml']} and {R['testset']['courses']['os']} source units). The first refusal-gate calibration used a dev split without hard negatives and gave a weak held-out result; we added harder cases (without moving existing ones) and documented it.
- LLM-judged metrics and vision descriptions need a working model; without one they are reported as not measured.

## What's next
Real-student pilots, embedding retrieval, per-question IRT difficulty calibration, and a course-author review UI for topic maps.

## Built with
Python, FastAPI, scikit-learn, PyMuPDF, python-pptx, faster-whisper, Pillow, Tailwind CSS, Cytoscape.js, Playwright, edge-tts, OpenAI-compatible LLMs.

## Credits
Started from an open-source study-companion repository (credited in the README) and borrowed ideas from the LearnFlow AI project (see `docs/MERGE_NOTES.md`).
"""
(ROOT / "DEVPOST_TEXT.md").write_text(text, encoding="utf-8")
print("wrote DEVPOST_TEXT.md")
