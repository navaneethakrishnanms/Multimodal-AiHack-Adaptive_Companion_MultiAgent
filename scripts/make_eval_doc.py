"""Render docs/EVALUATION.md from eval_report.json. Every number is read from the report, none typed here."""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
R = json.loads((ROOT / "eval_report.json").read_text(encoding="utf-8"))


def pct(x) -> str:
    return "n/a" if x is None else f"{100 * x:.1f}%"


def ms(d: dict, digits: int = 2) -> str:
    return f"{d['mean']:.{digits}f} ± {d['std']:.{digits}f}"


def sig(ci: list[float]) -> str:
    return "CI excludes 0" if ci[0] > 0 or ci[1] < 0 else "CI includes 0 (not significant)"


L: list[str] = []
w = L.append
w("# Evaluation results\n")
w(f"_Generated by `scripts/run_eval.py` on {R.get('generated_at', '?')} (took {R.get('elapsed_sec', '?')} s). "
  "This file is rendered from `eval_report.json`; re-run the script to refresh it. No number here is typed by hand._\n")
w(f"**Framework:** {R['framework']}.  \n"
  f"**LLM during this run:** {'online (' + R['llm']['model'] + ')' if R['llm']['healthy'] else 'offline — ' + (R['llm']['reason'] or 'not configured')}.\n")

t = R["testset"]
w("## Test set\n")
w(f"`tests/testset.json`: **{t['in_material']} in-material questions** with ground-truth source locations "
  f"(every unit that contains the answer is listed) and **{t['off_material']} off-material queries**, over two courses "
  f"(units per course: {', '.join(f'{k} = {v}' for k, v in t['courses'].items())}). Off-material queries include hard near-misses "
  "that share vocabulary with the course (e.g. Adam optimizer vs. learning rate, k-means vs. clusters). "
  "Splits (dev/test) are used only to calibrate the refusal gate.\n")

r = R["retrieval"]
w(f"## Retrieval (top-{r['k']}, the context the tutor sees)\n")
w("| Metric | Value |\n|---|---|")
w(f"| Cases | {r['cases']} |\n| Hit rate | {pct(r['hit_rate'])} |\n| MRR | {r['mrr']:.3f} |\n"
  f"| Context precision (ID-based) | {r['context_precision']:.3f} |\n| Context recall (ID-based) | {r['context_recall']:.3f} |\n")
w("Context precision/recall use the RAGAS definitions with unit IDs as relevance labels (no LLM needed).\n")

g = R["retrieval_gate"]
w("## Refusal gate (off-material queries)\n")
w(f"The gate is a two-feature rule chosen on the **dev** split ({g['chosen_on']}). Thresholds: offline min_score = {g['min_score']}, "
  f"online min_score = {g['min_score_online']}, min_coverage = {g['min_coverage']}.\n")
w("| Held-out test split | In-material answered | Off-material refused |\n|---|---|---|")
w(f"| No gate | {pct(g['no_gate_baseline_test']['answered_in_material'])} | {pct(g['no_gate_baseline_test']['refused_off_material'])} |")
w(f"| Offline gate (strict) | {pct(g['test']['answered_in_material'])} | {pct(g['test']['refused_off_material'])} |")
w(f"| Online gate (recall-first, LLM is 2nd layer) | {pct(g['online_gate_test']['answered_in_material'])} | {pct(g['online_gate_test']['refused_off_material'])} |\n")
w(f"Test split sizes: {g['test']['n_in']} in-material, {g['test']['n_off']} off-material — small, so one query moves a rate by 5–11 points.\n")

gen = R.get("generation")
w("## Generation quality\n")
if not gen:
    w("Not run (`--skip-generation`).\n")
else:
    inm, ref = gen["in_material"], gen["refusal_end_to_end"]
    w(f"Tutor mode during this run: **{gen['mode']}**; answer mode: `{inm.get('answer_mode')}`.\n")
    w("| Metric | Value |\n|---|---|")
    w(f"| Answered (in-material) | {inm['answered']}/{inm['cases']} ({pct(inm['answer_rate'])}) |")
    w(f"| Citation precision (cited units that are ground-truth relevant) | {inm['citation_precision']:.3f} |")
    w(f"| Citation hit rate (≥1 relevant unit cited) | {pct(inm['citation_hit_rate'])} |")
    w(f"| End-to-end refusal of off-material | {ref['refused']}/{ref['cases']} ({pct(ref['rate'])}) |")
    for k, label in (("faithfulness", "Faithfulness"), ("answer_relevancy", "Answer relevancy")):
        v = gen[k]
        if v.get("status") == "skipped":
            w(f"| {label} | **not measured** — {v['reason']} |")
        else:
            w(f"| {label} | {v['score']} (n = {v['n']}; {v['method']}) |")
    w("")

a = R["assessment"]
w("## Assessment quality\n")
w(f"{a['assessments']} consecutive assessments for one simulated student (mode: {a['mode']}), {a['questions']} questions.\n")
w("| Check | Value |\n|---|---|")
w(f"| Verified (key checked) | {pct(a['verified_rate'])} — kinds: {a['verification_kinds']} |")
w(f"| Topic/source tags consistent | {pct(a['tag_consistency'])} |")
w(f"| Answer grounded in its source unit | {pct(a['answer_grounded_in_source'])} |")
w(f"| Repeated questions across assessments | {pct(a['repeat_rate_across_assessments'])} |")
w(f"| Types / difficulties | {a['types']} / {a['difficulties']} |\n")
if a["mode"] == "offline":
    w("> Offline mode builds cloze questions whose key is a literal span of the source, so key correctness and grounding are "
      "true by construction; this table therefore says little about LLM-written questions. Re-run with a working LLM for those.\n")

w("## Personalization (simulated students)\n")
first = next(iter(R["personalization"].values()))
cfg = first["config"]
w(f"Latent-gap students: {cfg['students']} per course, {cfg['sessions']} sessions × {cfg['per_session']} questions, "
  f"20–30% of topics hidden-unknown, slip {cfg['slip']}, guess {cfg['guess']}, review success {cfg['review_success']}, fixed seeds. "
  "Policies: **A** fixed curriculum order; **B** BKT weakest-first after a diagnostic pass; **C** B + RootCause "
  "(blame prerequisites → 2 probe questions from the same budget → repair path). Same latent student under every policy (paired). "
  "Mean ± std over students.\n")
for cname, res in R["personalization"].items():
    w(f"### Course `{cname}` ({res['topics']} topics; mean unknown {res['mean_unknown_topics']}, of which root causes {res['mean_root_unknown_topics']})\n")
    w("| Policy | F1 vs all unknown | F1 vs root-cause unknown | Precision (root) | Recall (root) | Questions to find 80% of root gaps | True gap closure | Repeat rate |\n|---|---|---|---|---|---|---|---|")
    for p, s in res["summary"].items():
        if "gain" in s:
            ttf = f"{ms(s['ttf_R'], 1)} ({s['ttf_R_reached_pct']}% reached)"
            w(f"| {p} | {ms(s['f1_U'])} | {ms(s['f1_R'])} | {ms(s['precision_R'])} | {ms(s['recall_R'])} | {ttf} | {ms(s['gain'])} | {pct(s['repeat_rate']['mean'])} |")
        else:
            ttf = f"{ms(s['ttf_R'], 1)} ({s['ttf_R_reached_pct']}% reached)"
            w(f"| {p} | {ms(s['f1_U'])} | {ms(s['f1_R'])} | {ms(s['precision_R'])} | {ms(s['recall_R'])} | {ttf} | — | — |")
    w("\nPaired differences, C minus baseline (mean, 95% bootstrap CI over students):\n")
    w("| Metric | C − B | C − A |\n|---|---|---|")
    for m in ("f1_R", "f1_U", "gain", "acc_last", "ttf_U"):
        b, a_ = res["paired_vs_baselines"][f"C_minus_B.{m}"], res["paired_vs_baselines"][f"C_minus_A.{m}"]
        w(f"| {m} | {b['mean_diff']:+.3f} {b['ci95']} — {sig(b['ci95'])} | {a_['mean_diff']:+.3f} {a_['ci95']} — {sig(a_['ci95'])} |")
    w("\nSensitivity (mean F1 vs root-cause unknown / true gap closure):\n")
    w("| Setting | A | B | C |\n|---|---|---|---|")
    for label, sv in res["sensitivity"].items():
        cells = " | ".join(f"{sv[p]['f1_R']:.2f} / {sv[p]['gain']:.2f}" for p in ("A_fixed", "B_bkt", "C_rootcause"))
        w(f"| {label} | {cells} |")
    w("")
w("**How to read this.** F1 is computed on the gap set each policy would show the student. For C (and the ablation row "
  "`B_rootfilter`) the set is restricted to root causes, because RootCause deliberately hides downstream symptoms; the "
  "'root-cause unknown' columns score every policy against exactly that target, the 'all unknown' columns against every hidden "
  "unknown topic. The ablation shows how much of C's gain comes from the filter alone. 'True gap closure' is the fraction of "
  "initially unknown topics the simulated student actually learned, which is the quantity personalization is meant to raise.\n")

w("## Limitations (read before quoting any number)\n")
w("- Simulated students encode our own assumptions (prerequisite structure, review success rate). Gains show the policy exploits "
  "prerequisite structure when it exists; they are not evidence about real learners.\n"
  "- The courses are small (13 and 6 source units, 15 and 10 topics) and the held-out gate split has 28 queries.\n"
  "- The first calibration of the refusal gate used a dev split without hard negatives and gave a poor held-out refusal rate; "
  "we added harder cases before re-running and did not move existing cases (history note in `tests/testset.json`).\n"
  "- LLM-judged metrics appear only when an LLM was reachable during the run; otherwise they are marked *not measured*.\n")

(ROOT / "docs").mkdir(exist_ok=True)
(ROOT / "docs" / "EVALUATION.md").write_text("\n".join(L), encoding="utf-8")
print("wrote docs/EVALUATION.md")
